const ChangeInvoiceStatusPrompt = ({ invoice, setDb, onClose }) => {
  const initial = String(invoice?.status || '').trim();
  const [status, setStatus] = useState(initial || '');

  const save = async () => {
    const hasApiSession = Boolean(String(localStorage.getItem('token') || '').trim() && String(localStorage.getItem('activeOrgId') || '').trim());
    const backendInvoiceId = String(invoice?.backendInvoiceId || '').trim();
    const nextStatus = String(status || '').trim();

    if (hasApiSession && backendInvoiceId) {
      try {
        const total = Number(invoice?.total ?? 0);
        const payload = {
          status: nextStatus,
          paidAmount: nextStatus === 'Paid' ? total : Number(invoice?.paidAmount ?? 0),
        };
        await updateInvoiceStatusApi(backendInvoiceId, payload);
      } catch (e) {
        alert(String(e?.message || 'Unable to sync invoice status to backend.'));
        return;
      }
    }

    setDb((prev) => {
      const invoices = Array.isArray(prev.invoices) ? prev.invoices : [];
      let nextPayments = Array.isArray(prev.payments) ? [...prev.payments] : [];
      const today = new Date().toISOString().slice(0, 10);

      const nextInvoices = invoices.map((inv) => {
        if (inv.id !== invoice.id) return inv;

        const next = { ...inv };

        next.status = nextStatus;
        if (nextStatus === 'Paid') {
          const total = Number(next.total ?? 0);
          const alreadyPaid = Number(next.paidAmount ?? 0);
          const balance = Math.max(0, total - alreadyPaid);
          next.paidAmount = total;

          // Keep accounting trail aligned when user force-marks as Paid.
          if (balance > 0.0001) {
            const paymentId = getNextNumericId(nextPayments);
            nextPayments.push({
              id: paymentId,
              companyId: Number(next.companyId ?? invoice?.companyId ?? 0),
              voucherType: 'invoice',
              voucherId: Number(next.id),
              direction: 'IN',
              date: today,
              amount: Number(balance.toFixed(2)),
              mode: 'Adjustment',
              reference: 'STATUS-PAID',
              notes: 'Auto-created when invoice status was changed to Paid.',
              autoGenerated: true,
              createdAt: new Date().toISOString(),
            });
          }
        }

        next.updatedAt = new Date().toISOString();
        return next;
      });
      return { ...prev, invoices: nextInvoices, payments: nextPayments };
    });

    onClose?.();
  };

  return (
    <div className="space-y-4">
      <div className="text-sm ui-muted">
        Select a status for <span className="font-semibold ui-fg">{invoice?.number}</span>
      </div>

      <div>
        <label className="ui-label">Status</label>
        <select
          value={status}
          onChange={(e) => setStatus(e.target.value)}
          className="ui-input"
        >
          <option value="">Auto (based on payments)</option>
          <option value="Draft">Draft</option>
          <option value="Paid">Paid</option>
          <option value="Cancelled">Cancelled</option>
        </select>
      </div>

      <div className="flex justify-end gap-2">
        <button
          type="button"
          onClick={() => onClose?.()}
          className="ui-btn ui-btn-secondary"
        >
          Cancel
        </button>
        <button
          type="button"
          onClick={save}
          className="px-3 py-2 rounded-lg text-sm ui-primary-bg "
        >
          Save
        </button>
      </div>
    </div>
  );
};

/**
 * Past its due date and still carrying a balance.
 *
 * Both halves matter: a paid invoice whose due date has passed is not overdue,
 * and colouring it red would train people to ignore the colour.
 */
const isOverdue = (doc) => {
  const due = String(doc?.dueDate || '').slice(0, 10);
  if (!due) return false;
  const outstanding = Number(doc?.total ?? 0) - Number(doc?.paidAmount ?? 0);
  if (outstanding <= 0.005) return false;
  return due < new Date().toISOString().slice(0, 10);
};

